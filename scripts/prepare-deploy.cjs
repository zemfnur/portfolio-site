/* Create a static upload folder from the site's actual local dependencies.
 * No dependencies, network access, source transformations, or deployment. */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'dist');
const manifestPath = path.join(root, 'deployment-manifest.json');
const pages = ['index.html', 'about.html', ...fs.readdirSync(path.join(root, 'projects')).filter(p => p.endsWith('.html')).map(p => `projects/${p}`)];
const files = new Set();
const external = new Set();
const missing = [];
const warnings = [];
const optional = new Set(['assets/video/hero.mp4']);
const decode = s => s.replace(/&amp;/g, '&').replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n));

function reference(from, raw) {
  const value = decode(raw.trim());
  if (!value || /^(?:#|data:|mailto:|tel:|javascript:)/i.test(value)) return;
  if (/^(?:https?:)?\/\//i.test(value)) { external.add(value); return; }
  const local = decodeURIComponent(value.split(/[?#]/)[0]);
  const resolved = path.resolve(path.dirname(path.join(root, from)), local);
  if (!resolved.startsWith(root + path.sep)) throw new Error(`Path outside project: ${from}: ${value}`);
  visit(path.relative(root, resolved).split(path.sep).join('/'), from);
}

function visit(name, from = 'entry') {
  if (files.has(name)) return;
  const full = path.join(root, name);
  if (!fs.existsSync(full)) {
    const message = `${from} -> ${name}`;
    (optional.has(name) ? warnings : missing).push(message);
    return;
  }
  // Check exact spelling even on Windows: deployment servers are case sensitive.
  let parent = root;
  for (const part of name.split('/')) {
    if (!fs.readdirSync(parent).includes(part)) throw new Error(`Case mismatch: ${name}`);
    parent = path.join(parent, part);
  }
  if (!fs.statSync(full).isFile()) throw new Error(`Expected a file: ${name}`);
  files.add(name);
  const ext = path.extname(name);
  if (!['.html', '.css', '.js', '.webmanifest', '.svg'].includes(ext)) return;
  const source = fs.readFileSync(full, 'utf8');
  if (ext === '.html' || ext === '.svg') {
    const markup = source.replace(/<!--[\s\S]*?-->/g, '');
    for (const match of markup.matchAll(/\b(?:src|href|poster)\s*=\s*["']([^"']+)["']/g)) reference(name, match[1]);
  }
  if (ext === '.css' || ext === '.html' || ext === '.svg') {
    for (const match of source.matchAll(/url\(\s*["']?([^\s"')]+)["']?\s*\)/g)) reference(name, match[1]);
  }
  if (ext === '.webmanifest') {
    for (const icon of JSON.parse(source).icons || []) reference(name, icon.src);
  }
  if (name === 'assets/fonts/fonts.css') {
    // Retain licenses when redistributing the fonts in the public upload.
    for (const license of fs.readdirSync(path.join(root, 'assets/fonts')).filter(p => p.endsWith('-OFL.txt'))) {
      visit(`assets/fonts/${license}`, name);
    }
  }
  if (name === 'gaming-animation/scene.js') {
    // Runtime strings in scene.js resolve relative to the script, not the page.
    for (const match of source.matchAll(/['"]((?:Background|Card)\/[^'"]+\.png)['"]/g)) reference(name, match[1]);
    for (let frame = 1; frame <= 8; frame++) reference(name, `squirrel/run/frame-0${frame}.png`);
  }
}

pages.forEach(p => visit(p));
if (missing.length) throw new Error(`Missing required files:\n${missing.join('\n')}`);
// Only clean a previous output produced by this script; never an arbitrary folder.
if (fs.existsSync(output)) {
  const marker = path.join(output, '.portfolio-deploy-output');
  if (!fs.existsSync(marker)) throw new Error('dist already exists without our marker; move it aside before preparing.');
  if (fs.realpathSync(output) !== output) throw new Error('Refusing to replace a linked dist directory.');
  fs.rmSync(output, { recursive: true });
}
fs.mkdirSync(output);
fs.writeFileSync(path.join(output, '.portfolio-deploy-output'), 'Generated by scripts/prepare-deploy.cjs\n');
fs.writeFileSync(path.join(output, '.nojekyll'), '');
const inventory = [...files].sort().map(name => {
  const target = path.join(output, name);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.copyFileSync(path.join(root, name), target);
  return { path: name, bytes: fs.statSync(target).size };
});
const bytes = inventory.reduce((sum, f) => sum + f.bytes, 0);
fs.writeFileSync(manifestPath, JSON.stringify({ pages, bytes, files: inventory, external: [...external].sort(), warnings: [...new Set(warnings)] }, null, 2) + '\n');
console.log(`Prepared dist: ${inventory.length} files, ${(bytes / 1024 / 1024).toFixed(2)} MiB.`);
console.log(`Largest files:\n${[...inventory].sort((a,b) => b.bytes-a.bytes).slice(0,5).map(f => `${(f.bytes / 1024 / 1024).toFixed(2)} MiB  ${f.path}`).join('\n')}`);
console.log(`External URLs: ${external.size}. Full inventory: deployment-manifest.json`);
for (const warning of new Set(warnings)) console.warn(`Intentional placeholder: ${warning}`);
